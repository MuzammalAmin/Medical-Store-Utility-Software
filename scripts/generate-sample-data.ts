function ean13(sequence: number): string {
  const body = `8961100${String(sequence).padStart(5, '0')}`;
  let sum = 0;
  for (let i = 0; i < body.length; i++) sum += Number(body.charAt(i)) * (i % 2 === 0 ? 1 : 3);
  return body + String((10 - (sum % 10)) % 10);
}

