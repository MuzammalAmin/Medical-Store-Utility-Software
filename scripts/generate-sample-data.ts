function toRow(seed: Seed, index: number): ItemImportRow {
  const [
    brand,
    generic,
    strength,
    form,
    company,
    category,
    tabs,
    strips,
    price,
    mode,
    rate,
    reorder,
    rx,
    expiry,
    qty,
    cost,
  ] = seed;
  const prefix = brand
    .replace(/[^A-Za-z]/g, '')
    .slice(0, 2)
    .toUpperCase();
  return {
    brand_name: brand,
    generic_name: generic,
    strength,
    form,
    company,
    category,
    barcode: ean13(index + 1),
    rack: `${String.fromCharCode(65 + (index % 6))}${(index % 8) + 1}`,
    tabs_per_strip: tabs,
    strips_per_box: strips,
    sale_price_box: price,
    gst_mode: mode,
    gst_rate: rate,
    reorder_level: reorder,
    rx_required: rx,
    batch_no: `${prefix}${expiry.slice(-2)}${expiry.slice(0, 2)}${String(index + 1).padStart(2, '0')}`,
    expiry,
    qty,
    qty_unit: 'box',
    cost_price_box: cost,
  };
}

